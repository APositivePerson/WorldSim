import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

test("v2 sculpt, skin maps, face controls and compatibility with the original rig", async ({ page }) => {
  await mkdir("artifacts/avatar-v2-review", { recursive: true });
  await page.setViewportSize({ width: 1600, height: 1100 });
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", msg => { if (msg.type() === "error") errors.push(msg.text()); });
  await page.goto("/?avatar=procedural");
  await page.getByLabel("基座模式").selectOption("fixed");
  await expect(page.getByTestId("skin-status")).toContainText("92 骨骼");
  await page.getByRole("button", { name: "暂停仿真" }).click();
  await page.getByRole("button", { name: "头肩细节" }).click();
  const canvas = page.locator("canvas");
  const shot = (name: string) => canvas.screenshot({ path: `artifacts/avatar-v2-review/${name}.png` });
  await page.getByLabel("载入兼容 GLB").setInputFiles("artifacts/avatar-v1/human-skinned.glb");
  await expect(page.getByTestId("skin-status")).toContainText("67 骨骼");
  await shot("head-v1");
  await page.getByRole("button", { name: "恢复内置蒙皮" }).click();
  await expect(page.getByTestId("skin-status")).toContainText("92 骨骼");
  const neutral = await shot("head-v2");
  await page.getByLabel("自然眨眼").uncheck();
  await page.getByLabel("闭眼", { exact: true }).fill("100");
  const blink = await shot("blink");
  expect(blink.equals(neutral)).toBe(false);
  await page.getByLabel("闭眼", { exact: true }).fill("0");
  await page.getByLabel("张嘴", { exact: true }).fill("55");
  await page.getByLabel("微笑", { exact: true }).fill("60");
  await page.getByLabel("抬眉", { exact: true }).fill("45");
  await shot("expression");
  expect(await page.evaluate(() => window.human!.getState().face.jawOpen)).toBe(.55);
  expect(await page.evaluate(() => window.human!.setFace({ blink: 2 }))).toBe(false);
  await page.getByRole("button", { name: "恢复自然表情" }).click();
  await page.getByRole("button", { name: "右手细节" }).click();
  await shot("hand-v2");
  await page.getByRole("button", { name: "默认视角" }).click();
  await shot("body-v2");
  expect(errors).toEqual([]);
});
