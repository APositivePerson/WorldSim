import {test,expect} from '@playwright/test';
test.use({video:{mode:'on',size:{width:1280,height:800}}});
test('sensory standing, physical head turn, closed-eye push, pause and oracle comparison',async({page})=>{
  await page.setViewportSize({width:1500,height:950});
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/?avatar=procedural');
  await expect(page.getByTestId('skin-status')).toContainText('GLB 已绑定');
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().time)).toBeGreaterThan(1);
  await page.getByLabel('感觉控制模式').selectOption('sensory');
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.sensory?.estimate.uncertainty.available)).toBe(4);
  await expect(page.getByRole('button',{name:'向前行走'})).toBeEnabled();
  await page.getByRole('button',{name:'头肩细节'}).click();
  await page.getByRole('button',{name:'转头并保持注视'}).click();
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.sensory!.gaze.yaw)).toBeLessThan(-.3);
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.sensory!.diagnostics.gazeError)).toBeLessThan(.02);
  await page.locator('.viewport').screenshot({path:'artifacts/sensory/head-eye.png'});
  await page.getByRole('button',{name:'暂停仿真'}).click();
  const paused=await page.evaluate(()=>({time:window.human!.getState().time,state:window.human!.getState().locomotion!.sensory}));
  await page.waitForTimeout(250);
  expect(await page.evaluate(()=>({time:window.human!.getState().time,state:window.human!.getState().locomotion!.sensory}))).toEqual(paused);
  await page.getByRole('button',{name:'继续仿真'}).click();
  await page.getByLabel('感觉条件').selectOption('closed');
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.sensory!.estimate.uncertainty.available)).toBe(3);
  await page.getByRole('button',{name:'默认视角'}).click();
  await page.getByRole('button',{name:'侧推对照 · 35 N / 120 ms',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().balancePush.peak)).toBeGreaterThan(.001);
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().balancePush.active)).toBe(false);
  await expect.poll(()=>page.evaluate(()=>Math.abs(window.human!.getState().locomotion!.pelvis[0]))).toBeLessThan(.005);
  const state=await page.evaluate(()=>window.human!.getState());
  expect(state.locomotion!.pelvis[2]).toBeGreaterThan(.89);
  expect(state.locomotion!.sensory!.estimate.uncertainty.rejected).toBeGreaterThan(0);
  await page.locator('.viewport').screenshot({path:'artifacts/sensory/closed-eye-recovery.png'});
  await page.getByLabel('感觉控制模式').selectOption('oracle');
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.sensory)).toBeNull();
  await expect(page.getByRole('button',{name:'向前行走'})).toBeEnabled();
  expect(errors).toEqual([]);
  const video=page.video();await page.close();await video?.saveAs('artifacts/sensory/standing-and-gaze.webm');
});
