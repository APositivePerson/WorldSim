import { test, expect } from "@playwright/test";
test.use({ video: { mode: "on", size: { width: 1280, height: 800 } } });

test("default continuous gait travels physically, shows actual speed, pauses and stops", async ({ page }) => {
  await page.setViewportSize({ width: 1500, height: 950 });
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
  await page.goto("/?avatar=procedural");
  await expect(page.getByTestId("skin-status")).toContainText("GLB 已绑定");
  await expect(page.getByRole("combobox",{name:"步态",exact:true})).toHaveValue("natural");
  await expect(page.getByLabel("参考前进速度")).toHaveValue("0.5");
  await expect(page.getByLabel("行走落脚学习",{exact:true})).toHaveValue("learn");
  await expect(page.getByLabel("足底滚动与蹬地",{exact:true})).toBeChecked();
  await expect(page.getByLabel("受扰落点调整",{exact:true})).toBeChecked();
  await page.getByRole("button",{name:"向前行走"}).click();
  await expect(page.getByLabel("足底滚动与蹬地",{exact:true})).toBeDisabled();
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.motion.actualSpeed),{timeout:15000}).toBeGreaterThan(.35);
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.steps),{timeout:20000}).toBeGreaterThan(8);
  const state=await page.evaluate(()=>window.human!.getState().locomotion!);
  expect(state.pelvis[1]).toBeLessThan(-2);expect(state.pelvis[2]).toBeGreaterThan(.88);
  expect(state.cerebellum.walking.updates).toBeGreaterThan(4);
  expect(state.cerebellum.walking.load.updates).toBeGreaterThan(100);
  expect(state.mechanics.rolling).toBe(true);
  await page.getByLabel("行走落脚学习",{exact:true}).selectOption("frozen");
  const frozen=await page.evaluate(()=>window.human!.getState().locomotion!.cerebellum.walking);
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.cerebellum.walking.samples)).toBeGreaterThan(frozen.samples);
  expect(await page.evaluate(()=>window.human!.getState().locomotion!.cerebellum.walking.updates)).toBe(frozen.updates);
  expect(await page.evaluate(()=>window.human!.getState().locomotion!.cerebellum.walking.load.updates)).toBe(frozen.load.updates);
  await page.getByLabel("行走落脚学习",{exact:true}).selectOption("learn");
  await page.locator(".viewport").screenshot({path:"artifacts/natural-walking.png"});
  await page.getByRole("button",{name:"步足近景"}).click();
  const feetStart=await page.evaluate(()=>window.human!.getState().time);
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().time),{timeout:12000}).toBeGreaterThan(feetStart+3);
  await page.locator(".viewport").screenshot({path:"artifacts/walking-feet.png"});
  await page.getByRole("button",{name:"默认视角"}).click();
  await page.getByRole("button",{name:"暂停仿真"}).click();
  const time=await page.evaluate(()=>window.human!.getState().time);
  await page.waitForTimeout(200);
  expect(await page.evaluate(()=>window.human!.getState().time)).toBe(time);
  await page.getByRole("button",{name:"继续仿真"}).click();
  await page.getByRole("button",{name:"停步并站稳"}).click();
  await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.settled),{timeout:20000}).toBe(true);
  await page.getByRole("combobox",{name:"步态",exact:true}).selectOption("careful");
  await expect(page.getByLabel("参考前进速度")).toHaveValue("0.03");
  expect(errors).toEqual([]);
  const video=page.video();await page.close();await video?.saveAs("artifacts/natural-walking.webm");
});
