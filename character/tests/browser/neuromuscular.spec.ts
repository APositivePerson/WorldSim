import {test,expect} from '@playwright/test';
test.use({video:{mode:'on',size:{width:1280,height:800}}});
test('ankle/full muscles and physical eye gaze are accessible, move and restore comparison',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1500,height:1000});await page.goto('/?avatar=procedural');
 await expect(page.getByTestId('skin-status')).toContainText('GLB 已绑定');
 await page.getByLabel('基座模式').selectOption('neuro');
 await expect(page.getByLabel('腿部驱动')).toBeVisible();
 await expect(page.getByTestId('skin-status')).toContainText('GLB 已绑定');
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().time)).toBeGreaterThan(1.5);
 await page.getByLabel('腿部驱动').selectOption('ankle');
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().legMuscles.motors.length)).toBe(4);
 await page.getByLabel('腿部驱动').selectOption('full');
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().legMuscles.muscles.filter(f=>f.active).length)).toBe(34);
 await expect.poll(()=>page.evaluate(()=>Math.max(...window.human!.getState().legMuscles.muscles.map(f=>f.force)))).toBeGreaterThan(100);
 await page.getByRole('button',{name:'头肩细节',exact:true}).click();
 await page.getByRole('button',{name:'物理转头并注视',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().physicalEyes.eyes.every(e=>e.angles[0]<-.3)),{timeout:15000}).toBe(true);
 await page.locator('.viewport').screenshot({path:'artifacts/neuromuscular/physical-eyes.png'});
 await page.getByRole('button',{name:'远处目标与头部回正',exact:true}).click();
 await page.getByRole('button',{name:'默认视角'}).click();
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().joints.find(j=>j.name==='neck_yaw')!.velocity)).toBeLessThan(.05);
 await page.getByLabel('感觉控制模式').selectOption('sensory');
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.sensory?.estimate.uncertainty.available)).toBe(4);
 await page.getByRole('button',{name:'向前行走',exact:false}).click();
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().locomotion!.steps),{timeout:30000}).toBeGreaterThan(4);
 const state=await page.evaluate(()=>window.human!.getState());
 expect(state.locomotion!.pelvis[2]).toBeGreaterThan(.88);expect(state.legMuscles.motors.every(m=>m.force===0)).toBe(true);
 await expect(page.getByLabel('腿部驱动')).toBeDisabled();
 await page.locator('.viewport').screenshot({path:'artifacts/neuromuscular/full-leg-walk.png'});
 await page.getByRole('button',{name:'停步并站稳',exact:false}).click();
 await expect(page.getByTestId('gait-mode')).toHaveText('stand',{timeout:25000});
 await page.getByLabel('腿部驱动').selectOption('servo');
 await expect.poll(()=>page.evaluate(()=>window.human!.getState().legMuscles.mode)).toBe('servo');
 await page.getByRole('button',{name:'暂停仿真'}).click();
 const paused=await page.evaluate(()=>window.human!.getState().physicalEyes);await page.waitForTimeout(200);
 expect(await page.evaluate(()=>window.human!.getState().physicalEyes)).toEqual(paused);expect(errors).toEqual([]);
 const video=page.video();await page.close();await video?.saveAs('artifacts/neuromuscular/full-leg-and-eyes.webm');
});
