import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
test("photographic scan, facial controls and physical pickup stay aligned", async ({ page }) => {
  test.skip(!existsSync("artifacts/scanned-private/runtime/eric.glb"), "Requires a locally licensed scan");
  test.setTimeout(180000);
  await mkdir("artifacts/scanned-private/review", { recursive: true });
  await page.setViewportSize({ width: 1600, height: 1100 });
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", msg => { if (msg.type() === "error") errors.push(msg.text()); });
  await page.goto("/");
  await expect(page.getByTestId("skin-status")).toContainText("真人扫描 Eric", { timeout: 45000 });
  await page.getByRole("button", { name: "暂停仿真" }).click();
  const canvas = page.locator("canvas");
  const shot = (name: string) => canvas.screenshot({ path: `artifacts/scanned-private/review/${name}.png` });
  await shot("standing");
  await page.getByRole("button", { name: "头肩细节" }).click();
  await shot("head");
  await page.getByLabel("自然眨眼").uncheck();
  await page.getByLabel("闭眼", { exact: true }).fill("100");
  await shot("blink");
  await page.getByRole("button", { name: "恢复自然表情" }).click();
  await page.getByRole("button", { name: "右手细节" }).click();
  await shot("hand");
  await page.getByLabel("基座模式").selectOption("grasp");
  await expect(page.getByTestId("skin-status")).toContainText("真人扫描 Eric", { timeout: 45000 });
  await page.getByRole("button", { name: "拿起杯子" }).click();
  await page.getByRole("button", { name: "抓取近景", exact: true }).click();
  await expect(page.getByTestId("grasp-stage")).toHaveText("holding", { timeout: 90000 });
  await page.getByRole("button", { name: "暂停仿真" }).click();
  await shot("cup");
  const state = await page.evaluate(() => window.human!.getState());
  expect(state.grasp!.liftHeight).toBeGreaterThan(.06);
  expect(state.grasp!.supportForce).toBeLessThan(.05);
  expect(errors).toEqual([]);
});
